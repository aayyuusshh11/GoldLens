"""Generate the data-quality and backtest-readiness reports (Phase 4).

Run:  py -3.13 -m quant.ingestion.generate_reports

Uses ONLY the bhavcopy files already in the repo; every number is measured.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from quant.data import find_bhavcopy_files, load_bhavcopy
from quant.ingestion import readiness, validation

REPO_ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    reports_dir = REPO_ROOT / "data" / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)

    files = find_bhavcopy_files(REPO_ROOT)
    if not files:
        print(json.dumps({"error": "no bhavcopy files found across data/raw/mcx or repo root"}, indent=2))
        return 1
    provenance = [(str(p), hashlib.sha256(p.read_bytes()).hexdigest()) for p in files]

    frame = load_bhavcopy(files)
    dq = validation.build_report(frame, provenance)
    dq_path = reports_dir / "DATA_QUALITY_REPORT.md"
    validation.write_report_md(dq, dq_path)
    docs_dir = REPO_ROOT / "docs"
    if docs_dir.exists():
        validation.write_report_md(dq, docs_dir / "DATA_QUALITY_REPORT.md")
    (reports_dir / "data_quality_report.json").write_text(
        json.dumps(dq, indent=2, default=str), encoding="utf-8")

    verified_fields = [
        "gst_rate_on_transaction_charges (verified: statutory 18% on transaction charges)",
        "tick_size_rupees_per_quote_unit (verified: MCX GOLD/GOLDM tick Rs 1)",
        "ctt_bps_on_sell_turnover (verified statutory 0.01% sell-side, Finance Act 2013 s.117)",
        "exchange_transaction_bps_on_turnover (verified: Rs 2.10/lakh = 0.0021%, MCX circular"
        " implementing SEBI/HO/MRD/TPD-1/P/CIR/2024/92, eff 1 Oct 2024)",
        "stamp_duty_buy_side_bps_on_turnover (verified: 0.002% buy-side only, Indian Stamp"
        " Rules 2019 / Finance Act 2019 s.9A, eff 1 Jul 2020)",
    ]
    unverified = [
        "brokerage_rupees_per_lot (broker contract note required)",
        "slippage_ticks (execution-policy decision, must come from trader)",
    ]
    engine_report = REPO_ROOT / "quant_report.json"
    audit = readiness.audit(
        frame,
        verified_cost_fields=verified_fields,
        unverified_cost_fields=unverified,
        engine_run_path=engine_report if engine_report.exists() else None,
    )
    audit_path = reports_dir / "BACKTEST_READINESS.json"
    audit_path.write_text(json.dumps(audit, indent=2, default=str), encoding="utf-8")
    lines = [
        "# Backtest Readiness Report",
        "",
        f"Generated: {audit['generated_at']} - verdict: **{audit['verdict']}**",
        "",
        "## Readiness Gates",
        "",
        "| Gate | Verdict | Measured | Requirement |",
        "|---|---|---|---|",
    ]
    for g in audit["gates"]:
        lines.append(f"| {g['gate']} | {g['verdict']} | {g['measured']} | {g['requirement']} |")

    m = audit.get("metrics", {})
    pairs_str = ", ".join(m.get("unique_eligible_contract_pairs", [])) or "none"
    pairs_obs_str = ", ".join(f"{k}: {v}" for k, v in m.get("valid_dated_spread_observations_by_pair", {}).items()) or "none"
    lines += [
        "",
        "## Historical Session & Spread Observations Breakdown (Pass 11 Audit)",
        "",
        "| Metric | Measured | Meaning / Requirement |",
        "|---|---|---|",
        f"| Distinct Trading Sessions in Raw Dataset | {m.get('distinct_trading_sessions', 0)} | Distinct calendar dates loaded from genuine exchange files |",
        f"| Valid Dated Spread Observations per Eligible Pair | {pairs_obs_str} | Sessions where both near and far legs traded with valid, non-stale closes |",
        f"| Unique Eligible Contract Pairs | {m.get('unique_eligible_contract_pairs_count', 0)} ({pairs_str}) | Same-family pairs passing expiry and liquidity filters |",
        f"| Observations Available for Rolling Z-Score | {m.get('observations_available_for_rolling_z', 0)} | Insufficient: requires >= {m.get('min_hist_days_required', 15)} sessions (window 30) for causal rolling z |",
        f"| Max Observations Available Before Decision | {m.get('observations_available_before_decision_max', 0)} | History available prior to each simulated decision |",
        f"| Actual Walk-Forward Evaluation Dates | {m.get('actual_walk_forward_evaluation_dates', 0)} | 0 folds runnable (requires >= 70 sessions for 3 expanding folds) |",
        f"| Trades Generated by Strategy Engine | {m.get('trades_generated_by_engine', 0)} | 0 trades (all signals refused honestly as NO TRADE due to insufficient history) |",
        "",
        "Cost-field provenance is maintained in `docs/COST_MODEL.md`.",
        "",
    ]
    md_content = "\n".join(lines)
    (reports_dir / "BACKTEST_READINESS.md").write_text(md_content, encoding="utf-8")
    if docs_dir.exists():
        (docs_dir / "BACKTEST_READINESS.md").write_text(md_content, encoding="utf-8")

    print(json.dumps({
        "dq_report": str(dq_path),
        "readiness_report": str(audit_path),
        "verdict": audit["verdict"],
        "files": [f.name for f in files],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
