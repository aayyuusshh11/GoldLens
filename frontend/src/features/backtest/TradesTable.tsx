import type { TradeDTO } from "../../types/api";
import { formatDateShort, formatPrice, formatRatio } from "../../lib/formatters/format";
import { MetricValue } from "../../components/primitives/MetricValue";
import { EmptyState } from "../../components/states/EmptyState";
import { StatusBadge } from "../../components/layout/Badges";

/**
 * TradesTable — renders exactly the trades the pipeline produced.
 * No exit yet → date/reason show "pending exit", gross P&L stays null and is
 * rendered as unavailable — never as 0 or a substituted number.
 */
export function TradesTable({ trades }: { trades: TradeDTO[] }) {
  if (trades.length === 0) {
    return (
      <EmptyState
        title="No trades in this run"
        body="Within the loaded history the signal engine never entered (e.g. rolling z had insufficient history, or thresholds were never crossed). Absence of trades is a real result — it is not filled with examples."
      />
    );
  }

  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[900px] text-left text-sm">
        <caption className="sr-only">Trades generated by the pipeline backtest</caption>
        <thead>
          <tr className="border-b border-line text-[11px] uppercase tracking-widest text-mute">
            <th scope="col" className="py-2 pr-3 font-semibold">Leg</th>
            <th scope="col" className="py-2 pr-3 font-semibold">Direction</th>
            <th scope="col" className="py-2 pr-3 font-semibold">Signal → execution</th>
            <th scope="col" className="py-2 pr-3 text-right font-semibold">Entry spread (₹)</th>
            <th scope="col" className="py-2 pr-3 text-right font-semibold">Entry z</th>
            <th scope="col" className="py-2 pr-3 font-semibold">Exit date / reason</th>
            <th scope="col" className="py-2 pr-3 text-right font-semibold">Gross P&amp;L (₹)</th>
            <th scope="col" className="py-2 text-right font-semibold">Holding</th>
          </tr>
        </thead>
        <tbody>
          {trades.map((trade, index) => (
            <tr
              key={`${trade.leg_symbol}-${trade.entry_signal_date}-${index}`}
              className="border-b border-line/50 align-top last:border-b-0 hover:bg-elevated/40"
            >
              <td className="py-2 pr-3 font-mono text-ink">{trade.leg_symbol}</td>
              <td className="py-2 pr-3">
                <StatusBadge tone={isLong(trade.direction) ? "pos" : "neg"}>{trade.direction}</StatusBadge>
              </td>
              <td className="py-2 pr-3 font-mono tabular text-ink">
                {formatDateShort(trade.entry_signal_date)} → {formatDateShort(trade.entry_exec_date)}
              </td>
              <td className="py-2 pr-3 text-right font-mono tabular text-ink">
                {formatPrice(trade.entry_spread)}
              </td>
              <td className="py-2 pr-3 text-right font-mono tabular text-ink">
                {trade.entry_z === null ? (
                  <span className="text-mute">not computed</span>
                ) : (
                  formatRatio(trade.entry_z)
                )}
              </td>
              <td className="py-2 pr-3 text-mute">
                {trade.exit_exec_date === null ? (
                  <span>
                    pending exit · {trade.exit_reason} · exit spread{" "}
                    {trade.exit_spread === null ? "not recorded" : formatPrice(trade.exit_spread)}
                  </span>
                ) : (
                  <span className="font-mono tabular text-ink">
                    {formatDateShort(trade.exit_exec_date)} · {trade.exit_reason}
                  </span>
                )}
              </td>
              <td className="py-2 pr-3 text-right">
                <MetricValue
                  value={trade.gross_pnl_rupees}
                  kind="signed_rupees"
                  tone="sign"
                  unavailable="Unavailable (no completed exit)"
                />
              </td>
              <td className="py-2 text-right font-mono tabular text-ink">{trade.holding_days} d</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function isLong(direction: string): boolean {
  const normalized = direction.toLowerCase();
  return normalized.startsWith("long") || normalized.startsWith("buy");
}
