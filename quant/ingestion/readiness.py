"""Backtest readiness audit (Phase 3 & Pass 11 of the ingestion plan).

Readiness is reported, never assumed: every gate is computed from the
dataset/engine on disk and each gate carries its verdict + the exact reason
it fails. If anything here says 'NOT READY', the backtest must not be
presented as a valid result (this mirrors the engine's own
diagnostics_only guard — defence in depth, not duplication).

Pass 11 correction:
Distinct trading sessions, valid dated spread observations per eligible pair,
and candidate pairs are strictly separated. 22 commodity symbols on 1 day
is 1 trading session, NOT 22 spread observations.
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path
from typing import Any

import pandas as pd

MIN_SPREAD_OBSERVATIONS = 30       # hard floor for a "valid backtest" verdict
RECOMMENDED_OBSERVATIONS = 100     # comfortable minimum for walk-forward
MIN_QUALIFIED_COST_FIELDS = 3      # turnover-critical: brokerage, exchange txn, ctt
MIN_HIST_DAYS_REQUIRED = 15        # rolling z warmup (30 // 2)


def _gate(name: str, passed: bool, measured: object, required: str) -> dict[str, object]:
    return {
        "gate": name,
        "verdict": "OK" if passed else "NOT OK",
        "measured": measured,
        "requirement": required,
    }


def extract_readiness_metrics(
    frame: pd.DataFrame,
    engine_run_path: Path | str | None = None,
) -> dict[str, object]:
    """Separately compute the distinct metrics required for readiness assessment.

    Disentangles:
    1. Distinct trading sessions in the raw dataset.
    2. Valid dated spread observations per eligible pair.
    3. Number of unique eligible contract pairs.
    4. Observations available for rolling z-score calculations.
    5. Observations available before each simulated decision.
    6. Actual walk-forward evaluation dates.
    7. Trades generated by the engine.
    """
    dates = sorted(set(frame["trade_date"].dropna())) if len(frame) else []
    n_sessions = len(dates)

    pair_observations: dict[str, int] = {}
    eligible_pairs: list[str] = []
    trades_count: int = 0
    wf_dates_count: int = 0

    if engine_run_path is not None:
        p = Path(engine_run_path)
        if p.exists():
            import json
            try:
                run = json.loads(p.read_text(encoding="utf-8"))
                if isinstance(run, dict) and isinstance(run.get("results"), dict):
                    for sym, res in run["results"].items():
                        near = res.get("near_expiry")
                        far = res.get("far_expiry")
                        pair_id = f"{sym}_near{str(near).replace('-', '')}_far{str(far).replace('-', '')}"
                        obs = int(res.get("spread_observations", 0))
                        pair_observations[pair_id] = obs
                        eligible_pairs.append(pair_id)
                        fs = res.get("full_summary", {})
                        trades_count += int(fs.get("trades", 0))
                        wf = res.get("walk_forward", {})
                        if isinstance(wf, dict) and wf.get("folds"):
                            for fold in wf["folds"]:
                                if isinstance(fold, dict):
                                    wf_dates_count += int(fold.get("sessions", 0))
            except Exception:
                pass

    # If not populated from engine run, calculate directly from frame
    if not pair_observations and not frame.empty:
        sub = frame[(~frame.get("stale", pd.Series(False, index=frame.index)).astype(bool))
                    & frame["close"].notna()]
        for sym in ("GOLDM", "GOLD"):
            sym_df = sub[sub["symbol"] == sym]
            if not sym_df.empty:
                expiries = sorted(sym_df["expiry_ts"].unique())
                if len(expiries) >= 2:
                    near_exp, far_exp = expiries[0], expiries[1]
                    near_dates = set(sym_df[sym_df["expiry_ts"] == near_exp]["trade_date"])
                    far_dates = set(sym_df[sym_df["expiry_ts"] == far_exp]["trade_date"])
                    joint_dates = near_dates & far_dates
                    if joint_dates:
                        pair_id = f"{sym}_near{near_exp:%Y%m%d}_far{far_exp:%Y%m%d}"
                        pair_observations[pair_id] = len(joint_dates)
                        eligible_pairs.append(pair_id)

    max_pair_obs = max(pair_observations.values()) if pair_observations else eligible_estimate(frame)
    obs_for_z = max_pair_obs
    obs_before_decision_max = max_pair_obs

    return {
        "distinct_trading_sessions": n_sessions,
        "valid_dated_spread_observations_by_pair": pair_observations,
        "unique_eligible_contract_pairs": eligible_pairs,
        "unique_eligible_contract_pairs_count": len(eligible_pairs),
        "observations_available_for_rolling_z": obs_for_z,
        "observations_available_before_decision_max": obs_before_decision_max,
        "actual_walk_forward_evaluation_dates": wf_dates_count,
        "trades_generated_by_engine": trades_count,
        "min_hist_days_required": MIN_HIST_DAYS_REQUIRED,
        "min_spread_observations_floor": MIN_SPREAD_OBSERVATIONS,
        "recommended_observations": RECOMMENDED_OBSERVATIONS,
    }


def audit(
    frame: pd.DataFrame,
    *,
    verified_cost_fields: list[str],
    unverified_cost_fields: list[str],
    eligibility_counts: dict[str, int] | None = None,
    engine_run_path: Path | str | None = None,
) -> dict[str, object]:
    """Run every readiness gate over the supplied (already-cleaned) frame.

    verified_cost_fields / unverified_cost_fields must come from a maintained
    table (see docs/COST_MODEL.md).
    """
    gates: list[dict[str, object]] = []
    dates = sorted(set(frame["trade_date"].dropna())) if len(frame) else []
    n_dates = len(dates)
    n_symbols = int(frame["symbol"].nunique()) if len(frame) else 0

    metrics = extract_readiness_metrics(frame, engine_run_path=engine_run_path)

    gates.append(_gate(
        "dataCoverage",
        n_dates > 0,
        f"{n_dates} distinct trade date(s), {len(frame)} cleaned FUTCOM rows, "
        f"{n_symbols} symbols",
        "at least 1 trading day loaded from exchange files",
    ))

    eligible = int((eligibility_counts or {}).get("eligible", metrics["observations_available_for_rolling_z"]))
    gates.append(_gate(
        "minSpreadObservations",
        eligible >= MIN_SPREAD_OBSERVATIONS,
        f"{eligible} valid dated spread session(s) "
        f"vs floor {MIN_SPREAD_OBSERVATIONS} / recommended {RECOMMENDED_OBSERVATIONS}",
        f">= {MIN_SPREAD_OBSERVATIONS} eligible spread sessions",
    ))

    walk_ok = eligible >= RECOMMENDED_OBSERVATIONS
    gates.append(_gate(
        "walkForwardViability",
        walk_ok,
        f"{eligible < RECOMMENDED_OBSERVATIONS and 'not ' or ''}viable with {eligible} observation(s) "
        f"(requires >= {RECOMMENDED_OBSERVATIONS} sessions for walk-forward)",
        f">= {RECOMMENDED_OBSERVATIONS} sessions to split train/validation and "
        "run the configured 3 walk-forward folds honestly",
    ))

    verif_ratio = (len(verified_cost_fields),
                   len(verified_cost_fields) + len(unverified_cost_fields))
    gates.append(_gate(
        "costInputsVerified",
        len(verified_cost_fields) >= MIN_QUALIFIED_COST_FIELDS
        and len(unverified_cost_fields) == 0,
        f"verified {verif_ratio[0]}/{verif_ratio[1]} cost inputs "
        f"(unverified: {', '.join(unverified_cost_fields) or 'none'})",
        "brokerage, exchange transaction charges and statutory taxes verified "
        "against broker schedule / exchange circular / statute",
    ))

    engine_ok = False
    engine_meta: object = "engine run not supplied"
    if engine_run_path is not None:
        p = Path(engine_run_path)
        if p.exists():
            import json
            try:
                run = json.loads(p.read_text(encoding="utf-8"))
                if isinstance(run, dict) and run.get("error"):
                    engine_meta = f"engine reported error: {run['error']}"
                elif isinstance(run, dict) and isinstance(run.get("results"), dict):
                    engine_ok = len(run["results"]) > 0
                    engine_meta = {
                        "symbols": sorted(run["results"].keys()),
                        "trading_days_loaded": run.get("trading_days_loaded"),
                    }
                else:
                    engine_meta = "unrecognized report structure"
            except Exception as err:  # noqa: BLE001
                engine_meta = f"unreadable: {err}"
        else:
            engine_meta = f"missing file {p}"
    gates.append(_gate(
        "engineRunClean",
        engine_ok,
        engine_meta,
        "quant_report.json parsed with at least one spread result and no error key",
    ))

    verdict = "READY" if all(g["verdict"] == "OK" for g in gates) else "NOT READY"
    return {
        "generated_at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "verdict": verdict,
        "metrics": metrics,
        "gates": gates,
    }


def eligible_estimate(frame: pd.DataFrame, target_symbol: str | None = None) -> int:
    """Tradable spread sessions for calendar spread backtesting.

    Measures the distinct trade dates for the target strategy symbol (e.g. GOLDM/GOLD)
    on which at least two expiries had priced, non-stale closes.

    Never sums candidate pairs across different symbols on the same date:
    22 commodity symbols on 1 day is 1 trading session, NOT 22 spread sessions.
    """
    if frame.empty:
        return 0
    sub = frame[(~frame.get("stale", pd.Series(False, index=frame.index)).astype(bool))
                & frame["close"].notna()]
    if sub.empty:
        return 0

    if target_symbol is not None:
        sub_sym = sub[sub["symbol"] == target_symbol.upper()]
        if sub_sym.empty:
            return 0
        counts = sub_sym.groupby("trade_date")["expiry_ts"].nunique()
        return int((counts >= 2).sum())

    # Check target bullion futures families first (GOLDM, then GOLD)
    for sym in ("GOLDM", "GOLD"):
        sym_sub = sub[sub["symbol"] == sym]
        if not sym_sub.empty:
            c = sym_sub.groupby("trade_date")["expiry_ts"].nunique()
            n = int((c >= 2).sum())
            if n > 0:
                return n

    # Fallback for synthetic single-symbol frames (e.g. unit tests with "GOLD" or generic symbol):
    # Take the max across any single symbol, NEVER sum across symbols
    per_sym = sub.groupby(["symbol", "trade_date"])["expiry_ts"].nunique()
    per_sym_sessions = (per_sym >= 2).groupby("symbol").sum()
    return int(per_sym_sessions.max()) if not per_sym_sessions.empty else 0
